import { conectarBanco } from './banco/index.js';
import { gerarHashSenha } from './senhas.js';

export const TABELAS_ESTOQUE = ['cartas', 'produtos', 'acessorios'];

// Tipos que mudam entre os bancos; o resto do esquema é igual
const TIPOS = {
  sqlite: {
    id: 'INTEGER PRIMARY KEY AUTOINCREMENT',
    real: 'REAL',
    inteiroGrande: 'INTEGER',
    criadoEm: "TEXT NOT NULL DEFAULT (datetime('now', 'localtime'))",
  },
  postgres: {
    // BY DEFAULT (e não ALWAYS) para a migração conseguir copiar os ids originais
    id: 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
    real: 'DOUBLE PRECISION',
    inteiroGrande: 'BIGINT',
    criadoEm: 'TIMESTAMP(0) NOT NULL DEFAULT LOCALTIMESTAMP(0)',
  },
};

function esquema(dialeto) {
  const t = TIPOS[dialeto];
  const camposEstoque = `
    preco          ${t.real}    NOT NULL DEFAULT 0 CHECK (preco >= 0),
    custo          ${t.real}    NOT NULL DEFAULT 0 CHECK (custo >= 0),
    quantidade     INTEGER NOT NULL DEFAULT 0 CHECK (quantidade >= 0),
    estoque_minimo INTEGER NOT NULL DEFAULT 0 CHECK (estoque_minimo >= 0),
    imagem         TEXT,
    criado_em      ${t.criadoEm}`;

  return `
  CREATE TABLE IF NOT EXISTS colecoes (
    id              ${t.id},
    nome            TEXT    NOT NULL UNIQUE,
    sigla           TEXT,
    serie           TEXT,
    data_lancamento TEXT,
    criado_em       ${t.criadoEm}
  );

  CREATE TABLE IF NOT EXISTS cartas (
    id             ${t.id},
    nome           TEXT    NOT NULL,
    colecao_id     INTEGER NOT NULL REFERENCES colecoes(id) ON DELETE RESTRICT,
    numero         TEXT,
    raridade       TEXT,
    condicao       TEXT,
    idioma         TEXT,${camposEstoque}
  );

  CREATE TABLE IF NOT EXISTS produtos (
    id             ${t.id},
    nome           TEXT    NOT NULL,
    colecao_id     INTEGER NOT NULL REFERENCES colecoes(id) ON DELETE RESTRICT,
    tipo           TEXT    NOT NULL,${camposEstoque}
  );

  CREATE TABLE IF NOT EXISTS acessorios (
    id             ${t.id},
    nome           TEXT    NOT NULL,
    categoria      TEXT    NOT NULL,
    marca          TEXT,${camposEstoque}
  );

  CREATE TABLE IF NOT EXISTS usuarios (
    id           ${t.id},
    nome         TEXT    NOT NULL,
    usuario      TEXT    NOT NULL,
    senha_hash   TEXT    NOT NULL,
    perfil       TEXT    NOT NULL DEFAULT 'vendedor' CHECK (perfil IN ('admin', 'vendedor')),
    ativo        INTEGER NOT NULL DEFAULT 1,
    trocar_senha INTEGER NOT NULL DEFAULT 0,
    criado_em    ${t.criadoEm}
  );
  -- Login único sem diferenciar maiúsculas/minúsculas ("Ana" e "ana" são o mesmo usuário)
  CREATE UNIQUE INDEX IF NOT EXISTS usuarios_login_unico ON usuarios (lower(usuario));

  -- Guarda só o hash do token da sessão: quem ler o banco não consegue usar o token
  CREATE TABLE IF NOT EXISTS sessoes (
    token_hash TEXT    PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    expira_em  ${t.inteiroGrande} NOT NULL
  );

  -- Histórico de entradas e saídas. Nome do item e do usuário ficam copiados para o
  -- histórico continuar legível mesmo depois que o item ou o usuário forem excluídos.
  CREATE TABLE IF NOT EXISTS movimentacoes (
    id                  ${t.id},
    recurso             TEXT    NOT NULL,
    item_id             INTEGER NOT NULL,
    item_nome           TEXT    NOT NULL,
    operacao            TEXT    NOT NULL CHECK (operacao IN ('entrada', 'saida')),
    motivo              TEXT    NOT NULL,
    quantidade          INTEGER NOT NULL CHECK (quantidade > 0),
    quantidade_anterior INTEGER NOT NULL,
    quantidade_nova     INTEGER NOT NULL,
    preco_unitario      ${t.real},
    custo_unitario      ${t.real},
    observacao          TEXT,
    usuario_id          INTEGER,
    usuario_nome        TEXT,
    criado_em           ${t.criadoEm}
  );
  CREATE INDEX IF NOT EXISTS idx_mov_item ON movimentacoes (recurso, item_id);
  CREATE INDEX IF NOT EXISTS idx_mov_data ON movimentacoes (criado_em);
`;
}

// Conecta ao PostgreSQL (se houver databaseUrl) ou ao SQLite, cria as tabelas que faltarem e,
// com o banco vazio, cadastra o administrador e os dados de exemplo
export async function abrirBanco({ databaseUrl, arquivoSqlite, dadosIniciais = true }) {
  const db = conectarBanco({ databaseUrl, arquivoSqlite });
  await db.executarScript(esquema(db.dialeto));
  await atualizarEsquema(db);
  if (dadosIniciais) {
    await criarAdministradorInicial(db);
    await popularDadosIniciais(db);
  }
  return db;
}

// Bancos SQLite criados por versões anteriores não têm as colunas novas: adiciona as que faltarem
async function atualizarEsquema(db) {
  if (db.dialeto !== 'sqlite') return;
  const novasColunas = {
    imagem: 'TEXT',
    custo: 'REAL NOT NULL DEFAULT 0 CHECK (custo >= 0)',
  };
  for (const tabela of TABELAS_ESTOQUE) {
    const existentes = (await db.consultar(`PRAGMA table_info(${tabela})`)).map((c) => c.name);
    for (const [coluna, definicao] of Object.entries(novasColunas)) {
      if (!existentes.includes(coluna)) await db.executarScript(`ALTER TABLE ${tabela} ADD COLUMN ${coluna} ${definicao}`);
    }
  }
}

// Sem nenhum usuário cadastrado, cria o "admin". A senha inicial deve ser trocada no primeiro acesso.
async function criarAdministradorInicial(db) {
  const { total } = await db.um('SELECT COUNT(*) AS total FROM usuarios');
  if (total > 0) return;
  const senha = process.env.ADMIN_SENHA_INICIAL || 'admin123';
  await db.executar(
    `INSERT INTO usuarios (nome, usuario, senha_hash, perfil, trocar_senha) VALUES ('Administrador', 'admin', ?, 'admin', 1)`,
    [gerarHashSenha(senha)]
  );
}

// Insere alguns registros de exemplo na primeira execução (banco vazio)
async function popularDadosIniciais(db) {
  const { total } = await db.um('SELECT COUNT(*) AS total FROM colecoes');
  if (total > 0) return;

  await db.transacao(async (tx) => {
    const inserir = async (sql, params) => (await tx.um(`${sql} RETURNING id`, params)).id;
    const novaColecao = (...v) => inserir('INSERT INTO colecoes (nome, sigla, serie, data_lancamento) VALUES (?, ?, ?, ?)', v);
    const novaCarta = (...v) =>
      inserir(
        `INSERT INTO cartas (nome, colecao_id, numero, raridade, condicao, idioma, preco, custo, quantidade, estoque_minimo)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
        v
      );
    const novoProduto = (...v) =>
      inserir('INSERT INTO produtos (nome, colecao_id, tipo, preco, custo, quantidade, estoque_minimo) VALUES (?, ?, ?, ?, ?, ?, ?)', v);
    const novoAcessorio = (...v) =>
      inserir('INSERT INTO acessorios (nome, categoria, marca, preco, custo, quantidade, estoque_minimo) VALUES (?, ?, ?, ?, ?, ?, ?)', v);

    const svi = await novaColecao('Escarlate e Violeta', 'SVI', 'Escarlate e Violeta', '2023-03-31');
    const mew = await novaColecao('151', 'MEW', 'Escarlate e Violeta', '2023-09-22');
    const pre = await novaColecao('Evoluções Prismáticas', 'PRE', 'Escarlate e Violeta', '2025-01-17');

    await novaCarta('Charizard ex', mew, '199/165', 'Special Illustration Rare', 'Near Mint (NM)', 'Inglês', 1200, 850, 2, 1);
    await novaCarta('Mew ex', mew, '151/165', 'Double Rare (ex)', 'Near Mint (NM)', 'Português', 45, 25, 6, 3);
    await novaCarta('Pikachu', mew, '025/165', 'Comum', 'Near Mint (NM)', 'Português', 3, 1, 8, 10);
    await novaCarta('Umbreon ex', pre, '161/131', 'Special Illustration Rare', 'Near Mint (NM)', 'Inglês', 2500, 1900, 1, 1);

    await novoProduto('Booster 151', mew, 'Booster', 35, 22, 48, 24);
    await novoProduto('ETB Evoluções Prismáticas', pre, 'Elite Trainer Box', 650, 480, 3, 5);
    await novoProduto('Booster Box Escarlate e Violeta', svi, 'Booster Display (Box)', 900, 680, 2, 1);

    await novoAcessorio('Sleeves Matte Preto (100 un.)', 'Sleeves', 'Dragon Shield', 90, 55, 15, 10);
    await novoAcessorio('Deck Box Alcove Flip', 'Deck Box', 'Ultra Pro', 60, 35, 4, 5);
    await novoAcessorio('Pasta 9 bolsos', 'Pasta/Binder', 'Ultra Pro', 150, 95, 6, 2);
    await novoAcessorio('Toploader 3x4 (25 un.)', 'Toploader', 'Ultra Pro', 25, 14, 30, 10);

    // Registra o estoque de exemplo no histórico, como faria um cadastro feito pela tela
    for (const tabela of TABELAS_ESTOQUE) {
      await tx.executar(
        `INSERT INTO movimentacoes (recurso, item_id, item_nome, operacao, motivo, quantidade, quantidade_anterior,
           quantidade_nova, custo_unitario, usuario_nome)
         SELECT '${tabela}', id, nome, 'entrada', 'Cadastro inicial', quantidade, 0, quantidade, custo, 'Sistema'
         FROM ${tabela} WHERE quantidade > 0`
      );
    }
  });
}
